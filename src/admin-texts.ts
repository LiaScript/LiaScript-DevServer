export const TEXTS: { [l in Lang]: Texts } = { de, en }

// the switch of the page (cookie), else the first of de or en the browser
// names; a browser that names neither gets English, a request without the
// header (scripts, check.js) German
export function langOf(req: http.IncomingMessage): Texts {
  const cookie = /(?:^|;\s*)lia-lang=(de|en)/.exec(String(req.headers.cookie || ''))
  if (cookie) return TEXTS[cookie[1] as Lang]
  const accept = req.headers['accept-language']
  if (!accept) return de
  for (const part of String(accept).split(',')) {
    const l = part.trim().slice(0, 2).toLowerCase()
    if (l === 'de' || l === 'en') return TEXTS[l]
  }
  return en
}
